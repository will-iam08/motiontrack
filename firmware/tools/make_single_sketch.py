#!/usr/bin/env python3
"""Builds firmware/MotionTrackSingle/MotionTrackSingle.ino from the Bluetooth
firmware in mobile/Firmware/MotionTrack, as one file for the Arduino IDE.

Run from anywhere after changing the Bluetooth firmware:

    python3 firmware/tools/make_single_sketch.py

Needs `unifdef` (included with macOS and the Xcode command line tools).
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "mobile", "Firmware", "MotionTrack")
OUTPUT = os.path.join(ROOT, "firmware", "MotionTrackSingle", "MotionTrackSingle.ino")

# Dependency order: each file only uses names defined in the files before it.
ORDER = [
    "WorkoutWire.h", "RepCounter.h", "GravityEstimate.h", "TiltRepCounter.h",
    "WristRepCounter.h", "ArmCurlCounter.h", "ShoulderPressCounter.h",
    "BackRowCounter.h", "HeartCheckIn.h", "config.h", "ExerciseFlow.h", "EventOutbox.h",
    "LocalSession.h", "Radio.h", "Radio.cpp", "Workout.cpp",
]

HEADER = """\
// MotionTrack tracker firmware (Bluetooth build for the Motion Log app), in one file.
// GENERATED by firmware/tools/make_single_sketch.py from mobile/Firmware/MotionTrack.
// Do not edit this file: change the files in mobile/Firmware/MotionTrack and rerun the script.
//
// Board: DOIT ESP32 DEVKIT V1, ESP32 Arduino core 2.0.17, partition scheme "Huge APP".
// Libraries: SparkFun MAX3010x 1.1.2, Adafruit SSD1306 2.5.17 (+ GFX, BusIO),
//            SoftWire 2.0.10, AsyncDelay 1.1.2.
// Wiring: OLED SDA21/SCL22, MPU6050 SDA32/SCL33, pulse sensor SDA25/SCL26, all on 3V3.
// The pulse sensor switch is HEART_SENSOR_INSTALLED in the config section below; while
// it is false, the heart-rate checks are skipped.

#define MOTIONTRACK_WEBSITE 0
"""


def main():
    local = set(os.listdir(SOURCE))
    includes, sections = [], []
    for name in ORDER:
        with open(os.path.join(SOURCE, name)) as f:
            text = f.read()
        # Keep only the Bluetooth build (MOTIONTRACK_WEBSITE == 0).
        text = subprocess.run(["unifdef", "-DMOTIONTRACK_WEBSITE=0"], input=text,
                              capture_output=True, text=True).stdout
        lines = []
        for line in text.splitlines():
            if line.strip() == "#pragma once":
                continue
            match = re.match(r'\s*#include\s*([<"])([^>"]+)[>"]', line)
            if match:
                if match.group(1) == '"' and match.group(2) in local:
                    continue  # merged into this file
                if line.strip() not in includes:
                    includes.append(line.strip())
                continue
            lines.append(line)
        sections.append(f"// ===== {name} =====\n" + "\n".join(lines).strip() + "\n")

    code = (HEADER + "\n".join(includes) + "\n\n"
            "// Everything is inside one namespace so the Arduino IDE does not try to\n"
            "// generate function prototypes for it.\n"
            "namespace motiontrack {\n\n" + "\n".join(sections) +
            "\n}  // namespace motiontrack\n\n"
            "void setup() { motiontrack::setupTracker(); }\n"
            "void loop() { motiontrack::updateTracker(); }\n")
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w") as f:
        f.write(code)
    print(f"Wrote {os.path.relpath(OUTPUT, ROOT)} ({len(code.splitlines())} lines)")


if __name__ == "__main__":
    sys.exit(main())
